import assert from 'node:assert/strict';
import { brazilianDates, noteDay } from '../src/lib/calendar-dates.ts';
import { makeInstallments, paymentTotals, paymentPlanSchema, daySchema } from '../src/lib/payment-plan.ts';

const plan = makeInstallments(10000, 3, '2026-01-31');
assert.deepEqual(plan.installments.map(x => x.amountCents), [3334, 3333, 3333]);
assert.deepEqual(plan.installments.map(x => x.dueDate), ['2026-01-31','2026-02-28','2026-03-31']);
assert.equal(makeInstallments(100, 2, '2028-01-31').installments[1].dueDate, '2028-02-29');
assert.equal(makeInstallments(100, 2, '2026-12-31').installments[1].dueDate, '2027-01-31');
assert.throws(() => makeInstallments(1, 2, '2026-01-01'));
assert.throws(() => makeInstallments(100, 0, '2026-01-01'));
assert.throws(() => makeInstallments(100, 61, '2026-01-01'));
assert.equal(daySchema.safeParse('2026-02-30').success, false);
assert.equal(paymentPlanSchema.safeParse({...plan, totalCents: 9000}).success, false);
assert.equal(paymentPlanSchema.safeParse({...plan, installments: [plan.installments[0],plan.installments[0]]}).success, false);
plan.installments[0].paidDate = '2026-01-30';
assert.deepEqual(paymentTotals(plan, '2026-03-01'), { received:3334, remaining:6666, overdue:3333, paidCount:1 });
assert.equal(paymentTotals(plan, '2026-02-28').overdue, 0);
plan.installments.forEach(x => x.paidDate = '2026-02-01');
assert.equal(paymentTotals(plan, '2026-12-01').remaining, 0);
plan.installments[0].paidDate = null;
assert.equal(paymentTotals(plan, '2026-12-01').remaining, 3334);
const dates = brazilianDates(2026);
for (const [title,date] of [['Páscoa','2026-04-05'],['Carnaval','2026-02-17'],['Corpus Christi','2026-06-04'],['Dia das Mães','2026-05-10'],['Dia dos Pais','2026-08-09'],['Black Friday','2026-11-27'],['Cyber Monday','2026-11-30']]) assert.equal(dates.find(x => x.title === title).date,date);
assert.equal(brazilianDates(2027).find(x => x.title === 'Páscoa').date, '2027-03-28');
assert.equal(dates.filter(x => x.date === '2026-10-12').length, 2);
assert.equal(dates.find(x => x.title === 'Carnaval').type, 'Ponto facultativo federal');
assert.equal(noteDay({data:{},createdAt:'2026-09-15T12:00:00'}), '2026-09-15');
assert.equal(noteDay({data:{date:'2026-08-09'},createdAt:'2026-09-15T12:00:00'}), '2026-08-09');
console.log('26 verificações aprovadas: parcelas, centavos, datas, totais, feriados móveis e notas antigas.');
